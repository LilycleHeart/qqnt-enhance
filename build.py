"""Build the SnowLora renderer bundle from the original LiteLoader plugin.

Usage:
    python build.py [original_plugin_dir]

Default original plugin dir points at the backed-up qq-enhance plugin.
Output: renderer.js next to this script.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(
    os.path.dirname(HERE),
    "..",
    "backups",
    "uninstall-20261109-1720",
    "LiteLoaderQQNT.bak",
    "plugins",
    "qq-enhance.off",
)


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def strip_exports(src):
    return re.sub(r"(?m)^export\s+", "", src)


def main():
    src = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    stickers = read(os.path.join(src, "renderer", "stickers.js"))
    index = read(os.path.join(src, "renderer", "index.js"))
    vue_bridge = read(os.path.join(HERE, "vue-bridge.js"))
    settings_ui = read(os.path.join(HERE, "settings-ui.js"))

    stickers = strip_exports(stickers)
    index = re.sub(
        r'(?m)^\s*import\s*\{[^}]*\}\s*from\s*["\']\./stickers\.js["\'];?\s*$',
        "",
        index,
    )
    index = index.replace(
        "export const onSettingWindowCreated = async view => {",
        "async function onSettingWindowCreated(view) {",
    )
    index = strip_exports(index)

    if re.search(r"(?m)^\s*(import|export)\s", stickers + index):
        raise SystemExit("unhandled import/export remains")
    if "window.qq_enhance" not in index:
        raise SystemExit("renderer index missing window.qq_enhance")

    header = (
        "// qq-enhance SnowLora adapter renderer (generated by build.py)\n"
        "// Source: LiteLoaderQQNT qq-enhance 1.2.0: stickers.js + index.js\n"
        "// Changes: remove ESM import/export, mount settings into the QQ settings window.\n\n"
    )
    out = header + stickers + "\n\n" + vue_bridge + "\n\n" + index + "\n\n" + settings_ui
    with open(os.path.join(HERE, "renderer.js"), "w", encoding="utf-8") as f:
        f.write(out)
    print("wrote renderer.js", len(out), "chars")


if __name__ == "__main__":
    main()
